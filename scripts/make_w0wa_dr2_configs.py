#!/usr/bin/env python3
"""Write configs/cobaya/{w0wa,lcdm}_desidr2_cmb_<sn>.yaml from the official DESI DR2 w0waCDM chains.

DESI DR2 BAO + CMB (Planck 2018 low-ℓ TT/EE, NPIPE CamSpec TTTEEE, ACT DR6 + Planck PR4 lensing) +
Pantheon+ / Union3 / DES-SN5YR, as in DESI DR2 Results II (arXiv:2503.14738), from the public chains'
``chain.updated.yaml`` (``data/desi_dr2/cobaya/base_w_wa/…``), verbatim except for the edits listed in
each file's header:

* the DESI-internal BAO binding ``desi_y3_cosmo_bindings…bao_likelihoods_v1p2.desi_bao_all`` (not
  public) → Cobaya's public ``bao.desi_dr2.desi_bao_all`` (the DR2 BAO measurements, all tracers);
* ``act_dr6_lenslike_v1_2.ACTDR6LensLike`` → ``act_dr6_lenslike.ACTDR6LensLike`` (same package, v1.2);
* ΛCDM partner: ``w`` = −1, ``wa`` = 0 fixed (same data and every other setting), for the
  Δχ²_MAP and Bayes-factor comparison of the two models.
"""

from __future__ import annotations

import copy
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "data/desi_dr2/cobaya/base_w_wa"
OUT = ROOT / "src/gpucosmo/configs/cobaya"
CMB = "planck2018-lowl-TT-clik_planck2018-lowl-EE-clik_planck-NPIPE-highl-CamSpec-TTTEEE_planck-act-dr6-lensing"
SN = {"pantheonplus": "pantheonplus", "union3": "union3", "desy5": "desy5sn"}
BINDING = "desi_y3_cosmo_bindings.cobaya_likelihoods.bao_likelihoods_v1p2.desi_bao_all"
PUBLIC_BAO = "bao.desi_dr2.desi_bao_all"
ACT_V12 = "act_dr6_lenslike_v1_2.ACTDR6LensLike"  # DESI's install of act_dr6_lenslike v1.2
ACT = "act_dr6_lenslike.ACTDR6LensLike"


def make(sn: str, model: str) -> Path:
    src = SRC / f"desi-bao-all_{SN[sn]}_{CMB}" / "chain.updated.yaml"
    info = copy.deepcopy(yaml.safe_load(src.read_text()))
    edits = [f"likelihood {BINDING} (DESI-internal, not public) -> {PUBLIC_BAO} (Cobaya's public DESI DR2 BAO)",
             f"likelihood key {ACT_V12} -> {ACT} (the same act_dr6_lenslike v1.2 under its package name)"]
    lik = {}
    for k, v in info["likelihood"].items():
        if k == BINDING:
            lik[PUBLIC_BAO] = {}
        elif k == ACT_V12:
            lik[ACT] = v
        else:
            lik[k] = v
    info["likelihood"] = lik
    if model == "lcdm":
        info["params"]["w"] = -1.0
        info["params"]["wa"] = 0.0
        edits.append("w = -1, wa = 0 fixed (ΛCDM partner of the w0waCDM chain; no public ΛCDM chain needed)")
    name = f"{model}_desidr2_cmb_{sn}"
    head = [f"# {name}: Cobaya input for gpucosmo-evidence (--analysis {name}).",
            f"# Source: DESI DR2 public chain base_w_wa/desi-bao-all_{SN[sn]}_{CMB}/chain.updated.yaml",
            "# Generated by scripts/make_w0wa_dr2_configs.py; edits:"] + [f"#   - {e}" for e in edits]
    out = OUT / f"{name}.yaml"
    out.write_text("\n".join(head) + "\n" + yaml.safe_dump(info, sort_keys=False))
    return out


def main() -> int:
    for sn in SN:
        for model in ("w0wa", "lcdm"):
            print("wrote", make(sn, model).relative_to(ROOT))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
